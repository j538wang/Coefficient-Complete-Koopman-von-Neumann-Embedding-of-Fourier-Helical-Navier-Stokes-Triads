#!/usr/bin/env python3
"""
Shellwise energy and helicity transfer diagnostics for the Fourier--helical
RHS reconstruction benchmark.

This script loads a sparse Fourier velocity field, computes:
  1. explicit Cartesian projected-pair RHS over the retained sparse modes;
  2. helical-triad reconstructed RHS over the same retained modes;
  3. shellwise energy transfer T_E(shell);
  4. shellwise helicity transfer T_H(shell);
  5. modewise RHS scatter and shellwise error figures.

It is suitable for both synthetic divergence-free fields and short-time evolved
TGV sparse fields generated by run_tgv128_short_time.py.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import time
import math

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from fluid_helical_utils import (
    load_modes_npz, save_json, cartesian_pair_rhs, helical_pair_rhs,
    relative_error, max_modewise_relative_error, dict_l2_norm,
    transversality_error, conjugate_symmetry_error, shell_energy_transfer,
    shell_helicity_transfer, dict_difference_norm, v_to_array, modes_energy,
)


def generate_synthetic_modes(kmax: int, seed: int, target_energy: float, k0: float):
    from fluid_helical_utils import project_incompressible, v_neg
    rng = np.random.default_rng(seed)
    modes = {}
    # Generate only one member of conjugate pair, then insert partner.
    for kx in range(-kmax, kmax + 1):
        for ky in range(-kmax, kmax + 1):
            for kz in range(-kmax, kmax + 1):
                k = (kx, ky, kz)
                if k == (0,0,0):
                    continue
                r = math.sqrt(kx*kx + ky*ky + kz*kz)
                if r > kmax + 1e-12:
                    continue
                # canonical representative: first nonzero component positive.
                if k in modes or v_neg(k) in modes:
                    continue
                kk = np.asarray(k, float)
                amp_env = (r*r) * math.exp(-0.5 * (r / k0)**2)
                z = (rng.normal(size=3) + 1j * rng.normal(size=3)) * amp_env
                u = project_incompressible(k, z)
                modes[k] = u
                modes[v_neg(k)] = np.conjugate(u)
    E = modes_energy(modes)
    scale = math.sqrt(target_energy / (E + 1e-300))
    for k in list(modes.keys()):
        modes[k] *= scale
    return modes, {"case": "synthetic_divergence_free", "kmax": kmax, "seed": seed, "target_energy": target_energy, "k0": k0}


def parse_args():
    p = argparse.ArgumentParser(description=__doc__)
    src = p.add_mutually_exclusive_group(required=True)
    src.add_argument("--modes", type=str, help="Sparse modes npz generated by run_tgv128_short_time.py or save_modes_npz.")
    src.add_argument("--synthetic", action="store_true", help="Generate a synthetic divergence-free Fourier field.")
    p.add_argument("--synthetic-kmax", type=int, default=6)
    p.add_argument("--synthetic-seed", type=int, default=7)
    p.add_argument("--synthetic-energy", type=float, default=1.0)
    p.add_argument("--synthetic-k0", type=float, default=2.8)
    p.add_argument("--out", type=str, default="results_shell_helicity_transfer")
    p.add_argument("--contrib-tol", type=float, default=0.0, help="Small contribution filter for helical reconstruction.")
    return p.parse_args()


def dict_to_shell_df(ref, triad):
    shells = sorted(set(ref.keys()) | set(triad.keys()))
    rows = []
    for sh in shells:
        r = ref.get(sh, 0.0)
        t = triad.get(sh, 0.0)
        rows.append({
            "shell": sh,
            "reference": r,
            "helical_triad": t,
            "absolute_difference": abs(t-r),
            "relative_difference": abs(t-r) / (abs(r) + 1e-300),
        })
    return pd.DataFrame(rows)


def main():
    args = parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    if args.synthetic:
        modes, metadata = generate_synthetic_modes(args.synthetic_kmax, args.synthetic_seed, args.synthetic_energy, args.synthetic_k0)
    else:
        modes, metadata = load_modes_npz(args.modes)
    print(f"Loaded modes: {len(modes)}")

    tic = time.time()
    rhs_ref, n_pairs = cartesian_pair_rhs(modes)
    t_ref = time.time() - tic
    print(f"Cartesian sparse pair RHS: {len(rhs_ref)} modes, pairs={n_pairs}, time={t_ref:.2f}s")

    tic = time.time()
    rhs_tri, n_hel, _ = helical_pair_rhs(modes, store_contributions=False, contrib_tol=args.contrib_tol)
    t_tri = time.time() - tic
    print(f"Helical RHS: {len(rhs_tri)} modes, helical contributions={n_hel}, time={t_tri:.2f}s")

    eps = relative_error(rhs_tri, rhs_ref)
    maxeps = max_modewise_relative_error(rhs_tri, rhs_ref)
    print(f"global RHS rel error = {eps:.3e}")

    TE_ref = shell_energy_transfer(modes, rhs_ref)
    TE_tri = shell_energy_transfer(modes, rhs_tri)
    TH_ref = shell_helicity_transfer(modes, rhs_ref)
    TH_tri = shell_helicity_transfer(modes, rhs_tri)
    dfE = dict_to_shell_df(TE_ref, TE_tri)
    dfH = dict_to_shell_df(TH_ref, TH_tri)
    dfE.to_csv(out / "shell_energy_transfer.csv", index=False)
    dfH.to_csv(out / "shell_helicity_transfer.csv", index=False)

    diag = {
        **metadata,
        "input_velocity_modes": len(modes),
        "rhs_modes_reference": len(rhs_ref),
        "rhs_modes_helical": len(rhs_tri),
        "cartesian_pair_contributions": n_pairs,
        "helical_amplitude_contributions": n_hel,
        "rhs_norm_reference": dict_l2_norm(rhs_ref),
        "rhs_norm_helical": dict_l2_norm(rhs_tri),
        "global_rhs_relative_error": eps,
        "max_modewise_rhs_relative_error": maxeps,
        "input_energy": modes_energy(modes),
        "input_transversality_error": transversality_error(modes),
        "input_conjugate_symmetry_error": conjugate_symmetry_error(modes),
        "rhs_transversality_error_reference": transversality_error(rhs_ref),
        "rhs_transversality_error_helical": transversality_error(rhs_tri),
        "rhs_conjugate_symmetry_error_reference": conjugate_symmetry_error(rhs_ref),
        "rhs_conjugate_symmetry_error_helical": conjugate_symmetry_error(rhs_tri),
        "total_energy_transfer_reference": float(sum(TE_ref.values())),
        "total_energy_transfer_helical": float(sum(TE_tri.values())),
        "total_helicity_transfer_reference": float(sum(TH_ref.values())),
        "total_helicity_transfer_helical": float(sum(TH_tri.values())),
        "max_shell_energy_transfer_abs_difference": float(dfE["absolute_difference"].max()) if not dfE.empty else 0.0,
        "max_shell_helicity_transfer_abs_difference": float(dfH["absolute_difference"].max()) if not dfH.empty else 0.0,
        "runtime_cartesian_seconds": t_ref,
        "runtime_helical_seconds": t_tri,
    }
    save_json(out / "shell_helicity_summary.json", diag)

    # Modewise scatter.
    rows = []
    z = np.zeros(3, dtype=complex)
    for k in sorted(set(rhs_ref.keys()) | set(rhs_tri.keys())):
        nr = np.linalg.norm(rhs_ref.get(k, z))
        nt = np.linalg.norm(rhs_tri.get(k, z))
        if nr > 0 or nt > 0:
            rows.append({"k": str(k), "ref_abs": nr, "triad_abs": nt, "abs_diff": np.linalg.norm(rhs_tri.get(k,z)-rhs_ref.get(k,z))})
    pd.DataFrame(rows).to_csv(out / "modewise_rhs_scatter.csv", index=False)

    fig, ax = plt.subplots(figsize=(5.2, 5.0))
    ref_abs = [r["ref_abs"] for r in rows]
    tri_abs = [r["triad_abs"] for r in rows]
    ax.loglog(ref_abs, tri_abs, marker="o", linestyle="none", markersize=3.0, alpha=0.55)
    lo = max(min([x for x in ref_abs + tri_abs if x > 0] + [1e-16]), 1e-18)
    hi = max(ref_abs + tri_abs + [1e-12])
    ax.loglog([lo, hi], [lo, hi], linestyle="--", linewidth=1.0)
    ax.set_xlabel("|N_ref(k)|")
    ax.set_ylabel("|N_triad(k)|")
    ax.set_title("Modewise nonlinear RHS reconstruction")
    ax.grid(True, which="both", alpha=0.3)
    fig.tight_layout()
    fig.savefig(out / "modewise_rhs_scatter.png", dpi=230)
    plt.close(fig)

    # Shellwise energy transfer figure.
    fig, ax = plt.subplots(figsize=(7.0, 4.4))
    x = dfE["shell"].to_numpy()
    ax.plot(x, dfE["reference"], marker="o", linestyle="-", label="Cartesian reference")
    ax.plot(x, dfE["helical_triad"], marker="s", linestyle="--", label="Helical triad")
    ax.axhline(0, color="0.3", linewidth=0.8)
    ax.set_xlabel("wavenumber shell")
    ax.set_ylabel("energy transfer T_E(shell)")
    ax.set_title("Shellwise nonlinear energy transfer")
    ax.grid(True, alpha=0.3)
    ax.legend(frameon=True)
    fig.tight_layout()
    fig.savefig(out / "shell_energy_transfer_ref_vs_triad.png", dpi=230)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(7.0, 4.4))
    ax.semilogy(x, dfE["absolute_difference"] + 1e-300, marker="o", linestyle="-")
    ax.set_xlabel("wavenumber shell")
    ax.set_ylabel("|T_E_triad - T_E_ref|")
    ax.set_title("Shellwise energy-transfer reconstruction error")
    ax.grid(True, which="both", alpha=0.3)
    fig.tight_layout()
    fig.savefig(out / "shell_energy_transfer_error.png", dpi=230)
    plt.close(fig)

    # Helicity transfer figure.
    fig, ax = plt.subplots(figsize=(7.0, 4.4))
    xh = dfH["shell"].to_numpy()
    ax.plot(xh, dfH["reference"], marker="o", linestyle="-", label="Cartesian reference")
    ax.plot(xh, dfH["helical_triad"], marker="s", linestyle="--", label="Helical triad")
    ax.axhline(0, color="0.3", linewidth=0.8)
    ax.set_xlabel("wavenumber shell")
    ax.set_ylabel("helicity transfer T_H(shell)")
    ax.set_title("Shellwise nonlinear helicity transfer")
    ax.grid(True, alpha=0.3)
    ax.legend(frameon=True)
    fig.tight_layout()
    fig.savefig(out / "shell_helicity_transfer_ref_vs_triad.png", dpi=230)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(7.0, 4.4))
    ax.semilogy(xh, dfH["absolute_difference"] + 1e-300, marker="o", linestyle="-")
    ax.set_xlabel("wavenumber shell")
    ax.set_ylabel("|T_H_triad - T_H_ref|")
    ax.set_title("Shellwise helicity-transfer reconstruction error")
    ax.grid(True, which="both", alpha=0.3)
    fig.tight_layout()
    fig.savefig(out / "shell_helicity_transfer_error.png", dpi=230)
    plt.close(fig)

    print(f"Saved outputs to: {out}")


if __name__ == "__main__":
    main()
